import * as fs from 'fs';
import * as path from 'path';
import * as ts from 'typescript';
import type { ResolvedConfig } from '../config';
import { ensureDir, isInside, rmrf, SOURCE_EXT, walk } from '../util/fs';

/**
 * Sandboxing of the test suite (thesis Sec. 4.1, "Runtime-first design").
 *
 * The original test sources are never modified. Every execution runs against a
 * temporary copy under `<sandboxDir>/<run>/<name>/` (default `.mutants/`) in which
 *   - imports of `@playwright/test` are redirected to the MultilayerMT runtime
 *     fixture (which registers DOM / network mutations through Playwright hooks),
 *   - relative imports that leave the test directory are made absolute,
 *   - for test-script mutants, one file is replaced by its AST-mutated variant.
 * A generated wrapper config points Playwright at the copy.
 */

export interface Sandbox {
  name: string;
  dir: string;
  testDir: string;
  configFile: string;
}

export const FIXTURE_MODULE = path.resolve(__dirname, '../runtime/fixture.js');
const PLAYWRIGHT_SPECIFIERS = new Set(['@playwright/test', 'playwright/test']);

function toPosix(p: string): string {
  return p.split(path.sep).join('/');
}

/** Rewrite module specifiers of one source file. */
export function rewriteImports(source: string, fileName: string, origFile: string, origTestDir: string, fixtureModule = FIXTURE_MODULE): string {
  const sf = ts.createSourceFile(fileName, source, ts.ScriptTarget.Latest, true);
  const edits: { start: number; end: number; text: string }[] = [];

  const handle = (lit: ts.Node | undefined) => {
    if (!lit || !(ts.isStringLiteral(lit) || ts.isNoSubstitutionTemplateLiteral(lit))) return;
    const spec = lit.text;
    let next: string | null = null;
    if (PLAYWRIGHT_SPECIFIERS.has(spec)) next = toPosix(fixtureModule);
    else if (spec.startsWith('.')) {
      const target = path.resolve(path.dirname(origFile), spec);
      if (!isInside(target, origTestDir) && path.resolve(target) !== path.resolve(origTestDir)) next = toPosix(target);
    }
    if (next !== null) {
      const q = lit.getText(sf)[0];
      edits.push({ start: lit.getStart(sf), end: lit.end, text: q + next + q });
    }
  };

  const visit = (n: ts.Node) => {
    if ((ts.isImportDeclaration(n) || ts.isExportDeclaration(n)) && n.moduleSpecifier) handle(n.moduleSpecifier);
    else if (ts.isImportEqualsDeclaration(n) && ts.isExternalModuleReference(n.moduleReference)) handle(n.moduleReference.expression);
    else if (ts.isCallExpression(n)) {
      const isRequire = ts.isIdentifier(n.expression) && n.expression.text === 'require';
      const isDynImport = n.expression.kind === ts.SyntaxKind.ImportKeyword;
      if ((isRequire || isDynImport) && n.arguments.length === 1) handle(n.arguments[0]);
    } else if (ts.isImportTypeNode(n) && ts.isLiteralTypeNode(n.argument)) handle(n.argument.literal);
    n.forEachChild(visit);
  };
  visit(sf);
  edits.sort((a, b) => b.start - a.start);
  let out = source;
  for (const e of edits) out = out.slice(0, e.start) + e.text + out.slice(e.end);
  return out;
}

function wrapperConfig(cfg: ResolvedConfig, sandboxTestDir: string): string {
  const origConfig = toPosix(cfg.abs.playwrightConfig.replace(/\.(c|m)?(t|j)s$/, ''));
  const J = JSON.stringify;
  return `// Generated by MultilayerMT. Do not edit.
import * as path from 'path';
import base from ${J(origConfig)};

const cfg: any = (base as any)?.default ?? base;
const ORIG_CONFIG_DIR = ${J(toPosix(path.dirname(cfg.abs.playwrightConfig)))};
const ORIG_TEST_DIR = ${J(toPosix(cfg.abs.testDir))};
const SANDBOX_TEST_DIR = ${J(toPosix(sandboxTestDir))};
const KEEP_WEB_SERVER = ${J(cfg.keepWebServer)};

const abs = (p: any) => (typeof p === 'string' && !path.isAbsolute(p) ? path.resolve(ORIG_CONFIG_DIR, p) : p);
const inSandbox = (p: string): string | null => {
  const a = path.resolve(ORIG_CONFIG_DIR, p);
  const rel = path.relative(ORIG_TEST_DIR, a);
  return !rel.startsWith('..') && !path.isAbsolute(rel) ? path.join(SANDBOX_TEST_DIR, rel) : null;
};
const remapTestDir = (p: any) => (typeof p === 'string' ? inSandbox(p) ?? SANDBOX_TEST_DIR : SANDBOX_TEST_DIR);
const remapPath = (p: any) => (typeof p === 'string' ? inSandbox(p) ?? abs(p) : p);

const outputDir = process.env.MLMT_PW_OUTPUT_DIR || path.join(SANDBOX_TEST_DIR, '..', 'test-results');

export default {
  ...cfg,
  testDir: SANDBOX_TEST_DIR,
  outputDir,
  retries: 0,
  globalSetup: Array.isArray(cfg.globalSetup) ? cfg.globalSetup.map(abs) : abs(cfg.globalSetup),
  globalTeardown: Array.isArray(cfg.globalTeardown) ? cfg.globalTeardown.map(abs) : abs(cfg.globalTeardown),
  snapshotDir: remapPath(cfg.snapshotDir),
  webServer: KEEP_WEB_SERVER ? cfg.webServer : undefined,
  projects: Array.isArray(cfg.projects)
    ? cfg.projects.map((p: any) => ({ ...p, testDir: remapTestDir(p.testDir ?? cfg.testDir), outputDir, retries: 0 }))
    : undefined,
};
`;
}

/**
 * Create a sandbox copy of the test directory at `<sandboxDir>/<name>`.
 * @param files extra or replacing sources { relPath -> source } (mutated test
 *              files, in-memory generated tests)
 */
export function createSandbox(cfg: ResolvedConfig, name: string, files: Record<string, string> = {}): Sandbox {
  const dir = path.join(cfg.abs.sandboxDir, name);
  rmrf(dir);
  const testDir = path.join(dir, path.basename(cfg.abs.testDir) || 'tests');
  ensureDir(testDir);
  const written = new Set<string>();
  const writeSource = (relPosix: string, source: string) => {
    const dst = path.join(testDir, relPosix);
    ensureDir(path.dirname(dst));
    fs.writeFileSync(dst, rewriteImports(source, dst, path.join(cfg.abs.testDir, relPosix), cfg.abs.testDir));
    written.add(relPosix);
  };
  for (const rel of walk(cfg.abs.testDir)) {
    const relPosix = toPosix(rel);
    const src = path.join(cfg.abs.testDir, rel);
    if (SOURCE_EXT.test(rel)) writeSource(relPosix, files[relPosix] ?? fs.readFileSync(src, 'utf8'));
    else {
      const dst = path.join(testDir, rel);
      ensureDir(path.dirname(dst));
      fs.copyFileSync(src, dst);
    }
  }
  for (const [rel, source] of Object.entries(files)) {
    const relPosix = toPosix(rel);
    if (relPosix.startsWith('..') || path.isAbsolute(relPosix)) throw new Error(`test file path must be relative to testDir: ${rel}`);
    if (!written.has(relPosix)) writeSource(relPosix, source);
  }
  const configFile = path.join(dir, 'playwright.mlmt.config.ts');
  fs.writeFileSync(configFile, wrapperConfig(cfg, testDir));
  return { name, dir, testDir, configFile };
}

export function removeSandbox(s: Sandbox): void {
  rmrf(s.dir);
}
